function mapLocalizedEntry(entry, locale) {
    return {
        ...entry,
        title: entry.title[locale],
        summary: entry.summary[locale],
        ...(entry.intro ? { intro: entry.intro[locale] } : {}),
        ...(entry.highlights ? { highlights: entry.highlights[locale] } : {}),
        ...(entry.paragraphs ? { paragraphs: entry.paragraphs[locale] } : {}),
        ...(entry.type ? { type: entry.type[locale] } : {}),
        ...(entry.sourceLabel ? { sourceLabel: entry.sourceLabel[locale] } : {}),
    };
}

export function getProjects(locale) {
    return projectEntries.map((entry) => mapLocalizedEntry(entry, locale));
}

export function getProject(locale, slug) {
    const entry = projectEntries.find((item) => item.slug === slug);

    return entry ? mapLocalizedEntry(entry, locale) : null;
}

export function getProjectStaticSlugs() {
    return projectEntries.map((entry) => entry.slug);
}

export function getProjectDetailCopy(locale) {
    return projectDetails[locale] ?? projectDetails.ua;
}

export function getMediaItems(locale) {
    return mediaEntries.map((entry) => mapLocalizedEntry(entry, locale));
}

export function getMediaItem(locale, slug) {
    const entry = mediaEntries.find((item) => item.slug === slug);

    return entry ? mapLocalizedEntry(entry, locale) : null;
}

export function getMediaStaticSlugs() {
    return mediaEntries.map((entry) => entry.slug);
}

export function getMediaDetailCopy(locale) {
    return mediaDetails[locale] ?? mediaDetails.ua;
}
